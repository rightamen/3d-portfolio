// English is the server's own wording, so it needs no table: an untranslated
// key falls through to `finding[field]`, which is that wording.
// Exported so a test can check the invariant this file's header states -- that
// `en` stays complete, because it is what every other language falls back to.
// The translator itself cannot show a gap: it answers `en[key] ?? key`, so a
// missing Chinese string renders as English and looks deliberate.
export const dictionaries = {
  en,
  ja: { ...ja, ...findingCopy.ja },
  zh: { ...zh, ...findingCopy.zh },
}

const locales = { en: 'en-US', ja: 'ja-JP', zh: 'zh-CN' }

const interpolate = (template, values) =>
  values
    ? String(template).replace(/\{(\w+)\}/g, (match, name) =>
        values[name] === undefined || values[name] === null ? match : String(values[name]),
      )
    : String(template)

// Missing keys fall through to English rather than rendering an empty button.
// The key itself is the last resort: it is ugly on purpose, so a gap shows up
// in a screenshot instead of hiding as blank space.
export const createAdminTranslator = (language) => {
  const table = dictionaries[language] || dictionaries[defaultLanguage]

  return (key, values) => interpolate(table[key] ?? en[key] ?? key, values)
}

export const getInitialAdminLanguage = () => {
  if (typeof window === 'undefined') return defaultLanguage

  // The console remembers its own choice first: an operator may well read the
  // public site in Japanese and work in Chinese. Falling back to the site's
  // language means a first visit still lands somewhere sensible.
  const stored =
    window.localStorage.getItem(adminLanguageKey) || window.localStorage.getItem(siteLanguageKey)
  if (languages.some((language) => language.code === stored)) return stored

  const browserLanguage = (window.navigator.language || '').toLowerCase()
  if (browserLanguage.startsWith('ja')) return 'ja'
  if (browserLanguage.startsWith('en')) return 'en'

  return defaultLanguage
}

export const storeAdminLanguage = (language) => {
  if (typeof window === 'undefined') return

  window.localStorage.setItem(adminLanguageKey, language)
  document.documentElement.lang = language === 'zh' ? 'zh-CN' : language === 'ja' ? 'ja' : 'en'
}

// Every number, date and duration the console prints goes through here. The
// helpers in components/admin/charts.js hard-coded en-US and English unit
// words, which is fine until the surrounding sentence is Japanese.
export const createAdminFormatters = (language, t) => {
  const locale = locales[language] || locales[defaultLanguage]

  const formatNumber = (value) => new Intl.NumberFormat(locale).format(Number(value) || 0)

  const compactNumber = (value) => {
    const number = Number(value) || 0
    if (Math.abs(number) < 1000) return String(number)
    if (Math.abs(number) < 1_000_000) {
      return `${(number / 1000).toFixed(number % 1000 === 0 ? 0 : 1)}K`
    }

    return `${(number / 1_000_000).toFixed(1)}M`
  }

  const formatDate = (value) => {
    if (!value) return ''

    const date = new Date(value)
    if (Number.isNaN(date.getTime())) return ''

    return new Intl.DateTimeFormat(locale, { dateStyle: 'medium', timeStyle: 'short' }).format(date)
  }

  const formatDay = (day) => {
    const date = new Date(`${day}T00:00:00Z`)
    if (Number.isNaN(date.getTime())) return day

    return new Intl.DateTimeFormat(locale, {
      day: 'numeric',
      month: 'short',
      timeZone: 'UTC',
    }).format(date)
  }

  const formatTime = (value) => {
    const date = new Date(value)
    return Number.isNaN(date.valueOf())
      ? null
      : date.toLocaleTimeString(locale, { hour: '2-digit', minute: '2-digit' })
  }

  const formatAge = (value) => {
    if (!value) return ''

    const then = new Date(value).getTime()
    if (Number.isNaN(then)) return ''

    const seconds = Math.max(0, Math.round((Date.now() - then) / 1000))
    if (seconds < 60) return t('time.justNow')
    if (seconds < 3600) return t('time.minutesAgo', { n: Math.floor(seconds / 60) })
    if (seconds < 86400) return t('time.hoursAgo', { n: Math.floor(seconds / 3600) })
    if (seconds < 86400 * 30) return t('time.daysAgo', { n: Math.floor(seconds / 86400) })

    return t('time.monthsAgo', { n: Math.floor(seconds / (86400 * 30)) })
  }

  const formatCountdown = (value) => {
    if (!value) return ''

    const then = new Date(value).getTime()
    if (Number.isNaN(then)) return ''

    const seconds = Math.round((then - Date.now()) / 1000)
    if (seconds <= 0) return t('time.expired')
    if (seconds < 60) return t('time.inUnderMinute')
    if (seconds < 3600) return t('time.inMinutes', { n: Math.floor(seconds / 60) })
    if (seconds < 86400) return t('time.inHours', { n: Math.floor(seconds / 3600) })

    return t('time.inDays', { n: Math.floor(seconds / 86400) })
  }

  const formatDuration = (seconds) => {
    const total = Math.max(0, Math.round(Number(seconds) || 0))
    const days = Math.floor(total / 86400)
    const hours = Math.floor((total % 86400) / 3600)
    const minutes = Math.floor((total % 3600) / 60)

    if (days) return t('time.durationDaysHours', { d: days, h: hours })
    if (hours) return t('time.durationHoursMinutes', { h: hours, m: minutes })
    if (minutes) return t('time.durationMinutes', { m: minutes })

    return t('time.durationSeconds', { s: total })
  }

  // Byte units are the same word in all three languages, so this one keeps the
  // shared implementation rather than a translated copy of "KB".
  const formatBytes = (value) => {
    const bytes = Number(value) || 0
    if (bytes < 1024) return `${bytes} B`

    const units = ['KB', 'MB', 'GB', 'TB']
    let size = bytes / 1024
    let unit = 0
    while (size >= 1024 && unit < units.length - 1) {
      size /= 1024
      unit += 1
    }

    return `${size.toFixed(size >= 100 || unit === 0 ? 0 : 1)} ${units[unit]}`
  }

  const formatFileSize = (size) => {
    if (!Number.isFinite(size) || size <= 0) return ''
    if (size < 1024 * 1024) return `${Math.max(1, Math.round(size / 1024))} KB`

    return `${(size / 1024 / 1024).toFixed(size > 20 * 1024 * 1024 ? 0 : 1)} MB`
  }

  return {
    compactNumber,
    formatAge,
    formatBytes,
    formatCountdown,
    formatDate,
    formatDay,
    formatDuration,
    formatFileSize,
    formatNumber,
    formatTime,
    locale,
  }
}

export const createAdminI18n = (language) => {
  const t = createAdminTranslator(language)

  return { fmt: createAdminFormatters(language, t), language, t }
}

// A working default so a section rendered outside the provider -- a unit test,
// a Storybook-style harness -- still prints words instead of throwing.
const fallbackI18n = createAdminI18n(defaultLanguage)

export const AdminI18nContext = createContext(fallbackI18n)

export const useAdminI18n = () => useContext(AdminI18nContext) || fallbackI18n

